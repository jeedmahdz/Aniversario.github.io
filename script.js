/* ================================
   LIGHTBOX
================================ */

function openLightbox(memoryIndex, photoIndex) {

    const memory = memories[memoryIndex];

    if (!memory) return;

    /*
        Si el elemento seleccionado es un video,
        no lo abrimos en el lightbox de imágenes.
    */

    if (/\.(mp4|webm|ogg)$/i.test(memory.photos[photoIndex])) {
        return;
    }

    currentMemoryIndex = memoryIndex;
    currentPhotoIndex = photoIndex;

    updateLightbox();

    lightbox.classList.add("active");
}


/* ================================
   ACTUALIZAR LIGHTBOX
================================ */

function updateLightbox() {

    const memory =
        memories[currentMemoryIndex];

    if (!memory) return;

    /*
        Obtener solamente imágenes
        para que las flechas del lightbox
        no intenten abrir videos.
    */

    const imagePhotos =
        memory.photos.filter(photo => {
            return !/\.(mp4|webm|ogg)$/i.test(photo);
        });

    const currentPhoto =
        memory.photos[currentPhotoIndex];

    /*
        Si por alguna razón el índice actual
        apunta a un video, buscamos la primera imagen.
    */

    if (!currentPhoto ||
        /\.(mp4|webm|ogg)$/i.test(currentPhoto)) {

        currentPhotoIndex =
            memory.photos.findIndex(photo => {
                return !/\.(mp4|webm|ogg)$/i.test(photo);
            });
    }

    lightboxImage.src =
        memory.photos[currentPhotoIndex];

    lightboxCounter.textContent =
        `${currentPhotoIndex + 1} / ${imagePhotos.length}`;
}


/* ================================
   SIGUIENTE FOTO
================================ */

function nextPhoto() {

    const memory =
        memories[currentMemoryIndex];

    if (!memory) return;

    const imageIndexes =
        memory.photos
            .map((photo, index) => ({
                photo,
                index
            }))
            .filter(item => {
                return !/\.(mp4|webm|ogg)$/i.test(item.photo);
            })
            .map(item => item.index);

    if (imageIndexes.length === 0) return;

    let currentPosition =
        imageIndexes.indexOf(currentPhotoIndex);

    currentPosition++;

    if (currentPosition >= imageIndexes.length) {
        currentPosition = 0;
    }

    currentPhotoIndex =
        imageIndexes[currentPosition];

    updateLightbox();
}


/* ================================
   FOTO ANTERIOR
================================ */

function previousPhoto() {

    const memory =
        memories[currentMemoryIndex];

    if (!memory) return;

    const imageIndexes =
        memory.photos
            .map((photo, index) => ({
                photo,
                index
            }))
            .filter(item => {
                return !/\.(mp4|webm|ogg)$/i.test(item.photo);
            })
            .map(item => item.index);

    if (imageIndexes.length === 0) return;

    let currentPosition =
        imageIndexes.indexOf(currentPhotoIndex);

    currentPosition--;

    if (currentPosition < 0) {
        currentPosition =
            imageIndexes.length - 1;
    }

    currentPhotoIndex =
        imageIndexes[currentPosition];

    updateLightbox();
}


