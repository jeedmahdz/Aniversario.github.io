/* ================================
   CREAR TARJETAS
================================ */

function createMemoryCards() {
    const grid = document.getElementById("memoryGrid");

    if (!grid) return;

    grid.innerHTML = "";

    memories.forEach((memory, index) => {

        const card = document.createElement("article");
        card.className = "memory-card";

        const collage = document.createElement("div");
        collage.className = "memory-card-collage";

        /*
            Para el cover solamente utilizamos imágenes.
            Los videos aparecerán dentro del recuerdo.
        */

        const photosOnly = memory.photos.filter(photo => {
            return !/\.(mp4|webm|ogg)$/i.test(photo);
        });

        const photoCount = Math.min(4, photosOnly.length);

        for (let i = 0; i < photoCount; i++) {

            const imageContainer = document.createElement("div");
            imageContainer.className = "memory-cover-photo";

            const image = document.createElement("img");

            image.src = photosOnly[i];
            image.alt = memory.title;

            imageContainer.appendChild(image);
            collage.appendChild(imageContainer);
        }

        /*
            Si solamente hay una foto,
            ocupa toda la tarjeta.
        */

        if (photoCount === 1) {

            collage.style.gridTemplateColumns = "1fr";
            collage.style.gridTemplateRows = "1fr";

            const singlePhoto = collage.querySelector(".memory-cover-photo");

            if (singlePhoto) {
                singlePhoto.style.gridColumn = "1 / 2";
                singlePhoto.style.gridRow = "1 / 2";
                singlePhoto.style.width = "100%";
                singlePhoto.style.height = "100%";
            }
        }

        /*
            Overlay de la tarjeta
        */

        const overlay = document.createElement("div");
        overlay.className = "memory-card-overlay";

        overlay.innerHTML = `
            <div class="memory-card-number">
                ${String(index + 1).padStart(2, "0")}
            </div>

            <div class="memory-card-info">
                <h3>${memory.title}</h3>
                <p>
                    ${memory.photos.length}
                    recuerdo${memory.photos.length !== 1 ? "s" : ""}
                    · <span>VER</span>
                </p>
            </div>

            <div class="memory-card-arrow">
                →
            </div>
        `;

        card.appendChild(collage);
        card.appendChild(overlay);

        card.addEventListener("click", () => {
            openMemory(index);
        });

        grid.appendChild(card);

        /*
            Si tiene más de 4 fotos,
            el cover cambia automáticamente.
        */

        if (photosOnly.length > 4) {
            startCoverAnimation(collage, photosOnly);
        }
    });
}


/* ================================
   ANIMACIÓN DEL COVER
================================ */

function startCoverAnimation(collage, photos) {

    if (photos.length <= 4) {
        return;
    }

    const imageContainers =
        collage.querySelectorAll(".memory-cover-photo");

    let currentStart = 0;

    function updateCover() {

        imageContainers.forEach((container, position) => {

            const image = container.querySelector("img");

            if (!image) return;

            const photoIndex =
                (currentStart + position) % photos.length;

            image.style.opacity = "0";

            setTimeout(() => {

                image.src = photos[photoIndex];

                image.style.opacity = "1";

            }, 300);
        });

        currentStart =
            (currentStart + 4) % photos.length;
    }

    const interval = setInterval(updateCover, 3000);

    coverIntervals.push(interval);
}


